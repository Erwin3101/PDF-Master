/**
 * Translates a dictionary key with optional `{placeholder}` interpolation.
 * @param {string} key
 * @param {Record<string, string|number>} [params]
 * @returns {string}
 */
export function t(key, params = {}) {
    const dict = TRANSLATIONS[AppState.lang] || TRANSLATIONS.es;
    let text = dict[key] ?? TRANSLATIONS.es[key] ?? key;
    for (const [k, v] of Object.entries(params)) {
        text = text.replaceAll(`{${k}}`, String(v));
    }
    return text;
}

/**
 * Applies translations to DOM attributes without destroying child icon nodes.
 * Uses [data-i18n-text] / [data-i18n-html] / [data-i18n-placeholder] / [data-i18n-title].
 */
export function applyI18n(root = document) {
    document.documentElement.lang = AppState.lang;
    const langText = document.getElementById('lang-btn-text');
    if (langText) {
        langText.textContent = AppState.lang.toUpperCase();
    }

    root.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n');
        const val = t(key);
        if (el.hasAttribute('data-i18n-html')) {
            el.innerHTML = val;
        } else {
            el.textContent = val;
        }
    });

    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.setAttribute('placeholder', t(key));
    });

    root.querySelectorAll('[data-i18n-title]').forEach((el) => {
        const key = el.getAttribute('data-i18n-title');
        const val = t(key);
        el.setAttribute('title', val);
        el.setAttribute('aria-label', val);
    });

    root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
        const key = el.getAttribute('data-i18n-aria');
        el.setAttribute('aria-label', t(key));
    });
}
